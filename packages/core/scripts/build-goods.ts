const GROUPS: Array<[GoodsKind, Def[]]> = [
  ['character', CHARACTER],
  ['slang', SLANG],
  ['category', CATEGORY],
  ['ip', IP],
  ['brand', BRAND],
  ['condition', CONDITION],
]

// 캐릭터가 작품보다 먼저 오면 "마리오"가 두 번 정의된다. 충돌 검사가 잡아준다.

const terms: GoodsTerm[] = []
const seenKo = new Map<string, string>()

for (const [kind, defs] of GROUPS) {
  for (const [ko, ja, jaAlt] of defs) {
    for (const k of ko) {
      if (k.length < 2) throw new Error(`한 글자 한글 표제어 금지: "${k}" (${ja})`)
      const prev = seenKo.get(k)
      if (prev && prev !== ja) throw new Error(`한글 표제어 충돌: "${k}" → ${prev} vs ${ja}`)
      seenKo.set(k, ja)
    }
    if (!ja) throw new Error(`일본어 누락: ${ko.join('/')}`)
    terms.push({ kind, ko: [...ko], ja, ...(jaAlt ? { jaAlt: [...jaAlt] } : {}) })
  }
}

